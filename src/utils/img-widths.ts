// عروض الصور المتجاوبة تُشتق من مقاس العرض الفعلي في CSS لا من أرقام تقريبية.
// السبب (16 أكتوبر 2026): PageSpeed نبّه «تحسين عرض الصور» لصورة الزوالي في «تسوق حسب القسم»:
// البلاطة 112px على الجوال × كثافة 1.75 (جهاز قياس Lighthouse) = 196px، وأقرب عرض متاح كان 240px،
// فتحمّلت الصفحة صورة أكبر من الحاجة بثلثها تقريباً. الحل الدائم: لكل مقاس CSS نولّد عرضاً لكل كثافة شائعة
// (1، 1.75 جهاز Lighthouse، 2، 3)، فيجد المتصفح دائماً ملفاً مطابقاً تقريباً مهما كان الجهاز.
// الاستخدام: <Image widths={dprWidths([112, 150])} sizes="(min-width: 1024px) 150px, 112px" />
// ويجب أن تطابق المقاسات الممرَّرة كل قيمة في sizes (وللقيم بنسبة vw مرّر أكبر مقاس تبلغه وأصغره).

/** كثافات الشاشة المستهدفة: 1 (حواسيب)، 1.75 (جهاز قياس Lighthouse للجوال)، 2 و3 (أغلب الهواتف). */
export const DPRS = [1, 1.75, 2, 3] as const;

/**
 * يُرجع قائمة عروض مرتبة بلا تكرار: كل مقاس CSS مضروباً في كل كثافة، مقرّباً لأعلى إلى مضاعف 8.
 * @param cssWidths مقاسات عرض الصورة في CSS (بالبكسل) كما تظهر في sizes
 * @param max حد أعلى اختياري (مثل العرض الأصلي للصورة) لا يُتجاوز
 */
export function dprWidths(cssWidths: number[], max?: number): number[] {
  const out = new Set<number>();
  for (const w of cssWidths) {
    for (const d of DPRS) {
      let px = Math.ceil((w * d) / 8) * 8;
      if (max && px > max) px = max;
      out.add(px);
    }
  }
  return [...out].sort((a, b) => a - b);
}
